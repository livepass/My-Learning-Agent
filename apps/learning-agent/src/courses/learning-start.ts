import { CourseStoreError, type CourseStore } from "./course-store.js";
import type { Course, LearningTask, StudyPlan } from "./types.js";

/**
 * E4.4a — 「开始学习」 / 「继续学习」.
 *
 * The unit of work is one (course, task) pair, and the invariants are:
 *
 * 1. A task has at most one live session: an existing `CourseSessionBinding`
 *    for the task is resumed, never duplicated.
 * 2. A session is never created before the request can be remembered. The
 *    `LearningStart` record is written first, so a crash or a failed binding
 *    leaves a nameable attempt rather than an orphan conversation.
 * 3. If the binding cannot be written after the session was created, the
 *    session is discarded (when it is still empty) and the request record is
 *    dropped. A failure is never reported as "learning started".
 * 4. Task completion is untouched: starting sets `pending → in_progress`, and
 *    nothing here can mark a task `completed`.
 */

export interface LearningStartInput {
	courseId: string;
	taskId?: string | null;
	/** Client-provided idempotency key; generated by the route when absent. */
	requestId: string;
}

export interface LearningStartDeps {
	courseStore: CourseStore;
	sessionExists: (sessionId: string) => Promise<boolean>;
	/** `deleting`/`deleted` from the session lifecycle registry. */
	sessionState: (sessionId: string) => "deleting" | "deleted" | null;
	/**
	 * Create a session through the existing Agent queue. `null` means the queue
	 * was busy and the caller already answered (409); nothing was created.
	 */
	createSession: () => Promise<{ sessionId: string; previousSessionId: string } | null>;
	/** Compensating delete of a session this request created seconds ago. */
	discardSession: (sessionId: string, previousSessionId: string) => Promise<{ discarded: boolean; reason?: string }>;
	/** Switch the runtime to a resumed session; creation already switches. */
	activateSession: (sessionId: string) => Promise<"ok" | "busy" | "unavailable">;
	/** B2: idempotent create; an existing record is returned untouched. */
	initializeLearningRecord: (
		sessionId: string,
		goalId: string | null,
	) => Promise<{ created: boolean; checkpoint: { revision: number; status: string; step: string } | null }>;
}

export interface LearningStartTaskView {
	task_id: string;
	title: string;
	status: string;
	stage_id: string | null;
	plan_id: string | null;
	estimated_minutes: number | null;
	concept_ids: string[];
	concept_labels?: string[];
}

export type LearningStartOutcome =
	| {
		status: "ready";
		sessionId: string;
		course: Course;
		task: LearningStartTaskView | null;
		goalId: string | null;
		/** True when an existing task session was reopened. */
		resumed: boolean;
		/** True when this request created the session. */
		created: boolean;
		/** Non-fatal degradations (B2 init failed, task state not advanced). */
		warnings: string[];
		learning: {
			created: boolean;
			checkpoint: { revision: number; status: string; step: string } | null;
		};
	}
	| {
		status: "error";
		httpStatus: number;
		code: string;
		message: string;
		/** Present when a session was created and had to be discarded. */
		rolledBack?: boolean;
		/** Present when the session exists but is deliberately left unclassified. */
		sessionId?: string;
	};

export interface LearningStartScope {
	courseId: string;
	taskId: string | null;
}

function fail(httpStatus: number, code: string, message: string, extra: Partial<LearningStartOutcome & { status: "error" }> = {}): LearningStartOutcome {
	return { status: "error", httpStatus, code, message, ...extra };
}

function taskView(task: LearningTask): LearningStartTaskView {
	return {
		task_id: task.task_id,
		title: task.title,
		status: task.status,
		stage_id: task.stage_id,
		plan_id: task.plan_id,
		estimated_minutes: task.estimated_minutes,
		concept_ids: [...task.concept_ids],
		...(task.concept_labels ? { concept_labels: [...task.concept_labels] } : {}),
	};
}

/**
 * The goal a B2 record is opened with.
 *
 * Only a goal that the course explicitly binds may be attached, and the task's
 * plan goal wins because it is the one the plan was generated against. A plan
 * pointing at an unbound goal is treated as "no goal" instead of being copied:
 * B2 must never cite a relation the course does not have.
 */
function goalForTask(task: LearningTask | null, plan: StudyPlan | undefined, boundGoalIds: readonly string[]): string | null {
	if (!task) return null;
	if (plan?.goal_id && boundGoalIds.includes(plan.goal_id)) return plan.goal_id;
	return null;
}

/** In-process single flight: a double click pays for one session, not two. */
const flights = new Map<string, Promise<LearningStartOutcome>>();

function flightKey(scope: LearningStartScope, requestId: string): string {
	// Task starts are keyed by the task, so two different request ids for the
	// same task share one session. Free chat is keyed by the request id: each
	// deliberate "new conversation" is allowed to create its own session.
	return scope.taskId
		? `${scope.courseId}\u0000task\u0000${scope.taskId}`
		: `${scope.courseId}\u0000free\u0000${requestId}`;
}

export function startLearning(deps: LearningStartDeps, input: LearningStartInput): Promise<LearningStartOutcome> {
	const scope: LearningStartScope = {
		courseId: input.courseId,
		taskId: input.taskId ?? null,
	};
	const key = flightKey(scope, input.requestId);
	const existing = flights.get(key);
	if (existing) return existing;
	let run: Promise<LearningStartOutcome>;
	run = runStart(deps, input).finally(() => {
		if (flights.get(key) === run) flights.delete(key);
	});
	flights.set(key, run);
	return run;
}

async function runStart(deps: LearningStartDeps, input: LearningStartInput): Promise<LearningStartOutcome> {
	const { courseStore } = deps;
	let course: Course | undefined;
	try {
		course = await courseStore.getCourse(input.courseId);
	} catch (err) {
		if (err instanceof CourseStoreError) {
			return fail(503, "course_unavailable", "课程数据暂不可用，未开始学习。");
		}
		throw err;
	}
	if (!course) return fail(404, "course_not_found", "课程不存在");
	// E4.7-R1: an archived course is read-only. Without this, 「开始学习」 could
	// still create a session, advance a task and open a B2 record inside a course
	// the learner had archived — new evidence from a course that is supposed to
	// be history. Restoring the course is the only way back.
	if (course.status === "archived") {
		return fail(409, "course_archived", "课程已归档，恢复后才能继续学习。");
	}
	// A paused course is not part of today's plan. The card already disables
	// 「开始学习」 in that state; refusing here makes the API agree instead of
	// letting a direct call create a session the UI says is unavailable.
	if (course.status === "paused") {
		return fail(409, "course_paused", "课程已暂停，请先在课程页点击「继续课程」后再开始学习。");
	}

	let task: LearningTask | null = null;
	let plan: StudyPlan | undefined;
	const boundGoalIds = (await courseStore.listGoalBindings(input.courseId)).map((binding) => binding.goal_id);
	if (input.taskId) {
		task = await courseStore.getTask(input.courseId, input.taskId) ?? null;
		// A task from another course is indistinguishable from a missing one on
		// purpose: the response must not confirm that another course owns it.
		if (!task) return fail(404, "task_not_found", "学习任务不存在或不属于该课程");
		if (task.status === "completed") {
			return fail(409, "task_completed", "该任务已完成。如需复习请新建任务，或从每日推荐进入。");
		}
		if (task.plan_id) {
			plan = await courseStore.getPlan(input.courseId, task.plan_id);
			if (!plan) return fail(409, "plan_missing", "任务所属的学习计划不存在，不能开始学习");
			if (plan.status !== "active") {
				return fail(409, "plan_not_active", "任务所属的计划尚未确认启用，不能开始学习");
			}
		}
	}
	const goalId = goalForTask(task, plan, boundGoalIds);

	// 1. A task with a live session is 「继续学习」: reopen it, never fork it.
	if (task) {
		const bindings = await courseStore.listSessionBindings(input.courseId);
		// A file written before E4.4-R1 may hold several sessions for one task.
		// Continue the oldest one deterministically and report the rest; never
		// delete a conversation (or its B2 record) to "repair" the state here.
		const taskBindings = bindings
			.filter((binding) => binding.task_id === task.task_id)
			.sort((a, b) => a.created_at.localeCompare(b.created_at) || a.session_id.localeCompare(b.session_id));
		// The oldest LIVE session wins. A binding whose file vanished is dropped
		// (the conversation is already gone), but a duplicate that still exists
		// is never touched: it may hold the learner's other work.
		let bound: (typeof taskBindings)[number] | undefined;
		const stale: string[] = [];
		for (const candidate of taskBindings) {
			if (deps.sessionState(candidate.session_id)) {
				return fail(409, "session_unavailable", "该任务原会话正在删除或已删除，请重试。");
			}
			if (await deps.sessionExists(candidate.session_id)) {
				bound = candidate;
				break;
			}
			stale.push(candidate.session_id);
		}
		for (const sessionId of stale) await courseStore.removeSessionBinding(sessionId);
		const duplicateSessions = taskBindings
			.filter((binding) => binding.session_id !== bound?.session_id && !stale.includes(binding.session_id))
			.map((binding) => binding.session_id);
		if (bound) {
			const activated = await deps.activateSession(bound.session_id);
			if (activated === "busy") return fail(409, "session_busy", "当前有对话正在占用队列，请稍后重试。");
			if (activated === "unavailable") return fail(409, "session_unavailable", "该任务原会话已不可用，请重试。");
			return finish(deps, {
				course,
				task,
				goalId,
				sessionId: bound.session_id,
				resumed: true,
				created: false,
				// This path never reserved a request record; the binding is
				// already the idempotency proof.
				markStart: false,
				requestId: input.requestId,
				...(duplicateSessions.length > 0
					? {
						extraWarnings: [
							`该任务存在 ${duplicateSessions.length + 1} 个历史会话，本次继续最早的会话；其余会话与学习记录保持不变，请勿删除。`,
						],
					}
					: {}),
			});
		}
	}

	// 2. Reserve the request before touching the runtime.
	let reserved: Awaited<ReturnType<CourseStore["reserveLearningStart"]>>;
	try {
		reserved = await courseStore.reserveLearningStart({
			courseId: input.courseId,
			requestId: input.requestId,
			taskId: input.taskId ?? null,
		});
	} catch (err) {
		if (err instanceof CourseStoreError) {
			return err.code === "COURSE_CONFLICT"
				? fail(409, "request_conflict", "该请求 ID 已用于另一个开始学习请求")
				: fail(503, err.code.toLowerCase(), "课程数据暂不可用，未开始学习。");
		}
		throw err;
	}

	// 3. A previous attempt with this request id may have created a session but
	//    no binding (crash / storage failure). Finish that attempt instead of
	//    creating another conversation.
	let reusedAttempt = false;
	// Kept for the compensating delete: the runtime has to know which session
	// to fall back to if this one is discarded.
	let previousSessionId = "";
	let sessionId = reserved.record.session_id;
	if (sessionId) {
		const state = deps.sessionState(sessionId);
		if (state) return fail(409, "session_unavailable", "该请求创建的会话正在删除或已删除，请更换请求 ID 重试。", { sessionId });
		if (await deps.sessionExists(sessionId)) {
			reusedAttempt = true;
		} else {
			// The recovery window closed without a usable session: start clean.
			await courseStore.abortLearningStart(input.requestId);
			sessionId = null;
		}
	}

	if (!sessionId) {
		const created = await deps.createSession();
		if (!created) {
			// Nothing was created, so the reservation must go with the failure.
			// E4.7-R1: leaving it behind used to turn one busy click into a
			// permanent `creating` row, and the delete preview then reported a
			// 「尚未结束的学习启动请求」 that could never finish — the course
			// became undeletable even though no session, task or evidence existed.
			await courseStore.abortLearningStart(input.requestId).catch(() => undefined);
			return fail(409, "session_busy", "当前有对话正在占用队列，请稍后重试。");
		}
		sessionId = created.sessionId;
		previousSessionId = created.previousSessionId;
		try {
			await courseStore.attachLearningStartSession(input.requestId, sessionId);
		} catch {
			// The session exists but we cannot name it in our own log. Discard it
			// rather than leave a conversation nobody can trace back.
			const discarded = await deps.discardSession(sessionId, previousSessionId);
			await courseStore.abortLearningStart(input.requestId).catch(() => undefined);
			return fail(503, "start_record_failed", "无法记录本次学习开始，已撤销新会话，请重试。", {
				rolledBack: discarded.discarded,
				...(discarded.discarded ? {} : { sessionId }),
			});
		}
	}

	// 4. Bind. This is the step whose failure must not leave a misclassified
	//    session behind.
	try {
		await courseStore.bindSession({
			courseId: input.courseId,
			sessionId,
			taskId: task?.task_id ?? null,
			origin: task ? "task" : "free_question",
		});
	} catch (err) {
		const conflict = err instanceof CourseStoreError && err.code === "COURSE_SESSION_CONFLICT";
		if (conflict) {
			// Another attempt bound this exact session first (e.g. a lost reply).
			const context = await courseStore.getSessionContext(sessionId).catch(() => undefined);
			if (context && context.course.course_id === input.courseId
				&& (context.binding.task_id ?? null) === (task?.task_id ?? null)) {
				return finish(deps, {
					course, task, goalId, sessionId,
					resumed: true, created: false, markStart: true, requestId: input.requestId,
				});
			}
		}
		// Do not delete a session someone else may already be using.
		// Another process may have won the race and bound this task to its own
		// session. Converge on that session instead of failing a click that
		// would simply be retried.
		if (conflict && task) {
			const winners = (await courseStore.listSessionBindings(input.courseId))
				.filter((binding) => binding.task_id === task.task_id && binding.session_id !== sessionId);
			if (winners.length === 1 && await deps.sessionExists(winners[0].session_id)) {
				if (!reusedAttempt) await deps.discardSession(sessionId, previousSessionId).catch(() => undefined);
				await courseStore.abortLearningStart(input.requestId).catch(() => undefined);
				const activated = await deps.activateSession(winners[0].session_id);
				if (activated === "ok") {
					return finish(deps, {
						course,
						task,
						goalId,
						sessionId: winners[0].session_id,
						resumed: true,
						created: false,
						markStart: false,
						requestId: input.requestId,
					});
				}
			}
		}
		const discarded = reusedAttempt
			? { discarded: false, reason: "pre_existing_session" }
			: await deps.discardSession(sessionId, previousSessionId);
		await courseStore.abortLearningStart(input.requestId).catch(() => undefined);
		return fail(conflict ? 409 : 503, conflict ? "session_conflict" : "binding_failed",
			conflict
				? "该学习任务已绑定另一个会话，未改变原有归属。"
				: "学习会话未能关联到课程，已撤销本次开始。",
			{ rolledBack: discarded.discarded, ...(discarded.discarded ? {} : { sessionId }) });
	}

	return finish(deps, {
		course,
		task,
		goalId,
		sessionId,
		// A recovered attempt already had a conversation; the learner is
		// resuming it even though this request is what finally bound it.
		resumed: reusedAttempt,
		created: !reusedAttempt,
		markStart: true,
		requestId: input.requestId,
	});
}

async function finish(
	deps: LearningStartDeps,
	input: {
		course: Course;
		task: LearningTask | null;
		goalId: string | null;
		sessionId: string;
		resumed: boolean;
		created: boolean;
		/** False for a resume that never reserved a request record. */
		markStart: boolean;
		requestId: string;
		/** Reported before any degradation warning (e.g. legacy duplicates). */
		extraWarnings?: string[];
	},
): Promise<LearningStartOutcome> {
	const warnings: string[] = [...(input.extraWarnings ?? [])];
	// B2 first: a started session must be able to hold a formal question. The
	// record is created only if absent, so a resumed session keeps its history.
	let learning: { created: boolean; checkpoint: { revision: number; status: string; step: string } | null } =
		{ created: false, checkpoint: null };
	try {
		learning = await deps.initializeLearningRecord(input.sessionId, input.goalId);
	} catch {
		warnings.push("学习记录暂未初始化，可在会话中重试。");
	}

	// Task progress and task completion are different: this only moves a task
	// into `in_progress`, and only when it has not been started yet.
	let currentTask = input.task;
	if (input.task && input.task.status === "pending") {
		try {
			const updated = await deps.courseStore.updateTask(input.course.course_id, input.task.task_id, { status: "in_progress" });
			currentTask = updated;
		} catch {
			warnings.push("任务状态未更新为进行中，会话仍可用于学习。");
		}
	}

	if (input.markStart) {
		try {
			await deps.courseStore.markLearningStartReady(input.requestId, input.sessionId);
		} catch {
			warnings.push("开始学习记录未能标记完成，重复点击仍会回到本会话。");
		}
	}

	return {
		status: "ready",
		sessionId: input.sessionId,
		course: input.course,
		task: currentTask ? taskView(currentTask) : null,
		goalId: input.goalId,
		resumed: input.resumed,
		created: input.created,
		warnings,
		learning,
	};
}
