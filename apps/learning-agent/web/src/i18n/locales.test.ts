import { readFile, readdir } from "node:fs/promises";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import zhCN from "./locales/zh-CN.json";
import en from "./locales/en.json";

/**
 * E4.9b — translation resources for the learning UI.
 *
 * Runtime fallback (`fallbackLng: "zh-CN"`) hides a missing English key: the
 * screen silently shows Chinese. These checks fail the build-time test suite
 * instead, for the keys the learning system actually renders.
 *
 * Rules:
 * - a key used by the learning UI must exist in BOTH locales;
 * - plural keys follow each language's own rules (`_one`/`_other` in English,
 *   a single form in Chinese), so the two files are not compared literally;
 * - `{{variables}}` must match between the two locales of the same key;
 * - fixed Chinese in a learning page must be registered as an allowed exception.
 */

type Tree = Record<string, unknown>;
const zh = zhCN as Tree;
const enTree = en as Tree;

/** Every leaf as `dotted.path -> value`, keeping plural suffixes intact. */
function flatten(node: Tree, prefix = ""): Record<string, string> {
	const out: Record<string, string> = {};
	for (const [key, value] of Object.entries(node)) {
		const path = prefix ? `${prefix}.${key}` : key;
		if (value && typeof value === "object" && !Array.isArray(value)) {
			Object.assign(out, flatten(value as Tree, path));
		} else if (typeof value === "string") {
			out[path] = value;
		}
	}
	return out;
}

const zhFlat = flatten(zh);
const enFlat = flatten(enTree);

/** English plural suffixes are generated by i18next, not authored in Chinese. */
const PLURAL = /_(zero|one|two|few|many|other)$/;
const base = (key: string) => key.replace(PLURAL, "");

function pluralFamilies(flat: Record<string, string>): Set<string> {
	const out = new Set<string>();
	for (const key of Object.keys(flat)) if (PLURAL.test(key)) out.add(base(key));
	return out;
}

function variables(value: string): string[] {
	return [...value.matchAll(/\{\{\s*([\w.]+)\s*\}\}/g)].map((m) => m[1]!).sort();
}

/**
 * Groups the learning UI owns. A key here must exist in both locales; the
 * remaining Inno-era groups are out of scope for E4.9b (see the audit doc).
 */
const LEARNING_GROUPS = [
	"nav.today",
	"nav.learn",
	"nav.practice",
	"nav.profile",
	"nav.settingsPage",
	"nav.course",
	"shell.",
	"today.",
	"learn.",
	"practice.",
	"course.",
	"archive.",
	"profile.",
	"settings.",
	"common.",
];

function isLearningKey(key: string): boolean {
	return LEARNING_GROUPS.some((prefix) => key === prefix.replace(/\.$/, "") || key.startsWith(prefix));
}

describe("i18n learning resources", () => {
	it("has a Chinese and an English entry for every learning key", () => {
		const zhKeys = Object.keys(zhFlat).filter(isLearningKey);
		expect(zhKeys.length).toBeGreaterThan(0);
		const missing: string[] = [];
		for (const key of zhKeys) {
			if (PLURAL.test(key)) continue;
			if (enFlat[key] === undefined) missing.push(key);
		}
		expect(missing, `missing English keys: ${missing.join(", ")}`).toEqual([]);
	});

	it("does not define an English learning key without its Chinese source", () => {
		const enKeys = Object.keys(enFlat).filter(isLearningKey).filter((key) => !PLURAL.test(key));
		const missing = enKeys.filter((key) => zhFlat[key] === undefined);
		expect(missing, `missing Chinese keys: ${missing.join(", ")}`).toEqual([]);
	});

	it("treats plural keys by each language's own rules", () => {
		const enPlural = pluralFamilies(enFlat);
		const zhPlural = pluralFamilies(zhFlat);
		// A family in either file must resolve to a base key present in both.
		for (const family of new Set([...enPlural, ...zhPlural])) {
			expect(
				zhFlat[family] !== undefined || zhPlural.has(family),
				`plural family ${family} has no Chinese source`,
			).toBe(true);
			expect(
				enFlat[family] !== undefined || enPlural.has(family),
				`plural family ${family} has no English source`,
			).toBe(true);
		}
	});

	it("keeps template variables identical between locales", () => {
		const mismatched: string[] = [];
		for (const [key, zhValue] of Object.entries(zhFlat)) {
			if (!isLearningKey(key) || PLURAL.test(key)) continue;
			const enValue = enFlat[key];
			if (enValue === undefined) continue;
			const a = variables(zhValue);
			const b = variables(enValue);
			if (a.join(",") !== b.join(",")) mismatched.push(`${key} (${a} vs ${b})`);
		}
		expect(mismatched, `variable mismatch: ${mismatched.join("; ")}`).toEqual([]);
	});

	it("defines every literal key the learning code references", async () => {
		// A key that only exists as a `t("…", "中文")` fallback hides a missing
		// resource: the English UI would silently show Chinese. Every literal
		// reference in a learning component must resolve in both files.
		const root = new URL("../react/", import.meta.url);
		const files: string[] = [];
		async function walk(dir: URL, prefix = ""): Promise<void> {
			for (const entry of await readdir(dir, { withFileTypes: true })) {
				const child = new URL(`${entry.name}${entry.isDirectory() ? "/" : ""}`, dir);
				const path = `${prefix}${entry.name}`;
				if (entry.isDirectory()) await walk(child, `${path}/`);
				else if (/\.(tsx|ts)$/.test(entry.name) && !entry.name.includes(".test.")) files.push(path);
			}
		}
		await walk(root);

		const literal = /t\(\s*"([a-z][A-Za-z0-9_]*(?:\.[A-Za-z0-9_\-]+)+)"/g;
		const referenced = new Set<string>();
		for (const file of files) {
			const source = await readFile(new URL(file, root), "utf-8");
			for (const match of source.matchAll(literal)) referenced.add(match[1]!);
		}
		expect(referenced.size).toBeGreaterThan(0);

		const missingZh = [...referenced].filter((key) => zhFlat[key] === undefined);
		const missingEn = [...referenced].filter((key) => enFlat[key] === undefined);
		expect(missingZh, `referenced but missing in zh-CN: ${missingZh.join(", ")}`).toEqual([]);
		expect(missingEn, `referenced but missing in en: ${missingEn.join(", ")}`).toEqual([]);
	}, 30_000);

	it("validates dynamic enum keys used with template literals", () => {
		// Keys built at runtime (`t(\`course.status.${status}\`)`) cannot be found
		// by a literal scan, so the enumerated values are checked explicitly.
		const enums: Array<[string, string[]]> = [
			["course.status", ["in_progress", "paused", "completed", "archived"]],
			["practice.result", ["correct", "partial", "incorrect", "unknown"]],
		];
		const problems: string[] = [];
		for (const [prefix, values] of enums) {
			for (const value of values) {
				const key = `${prefix}.${value}`;
				if (zhFlat[key] === undefined) problems.push(`zh:${key}`);
				if (enFlat[key] === undefined) problems.push(`en:${key}`);
			}
		}
		expect(problems, `missing enum keys: ${problems.join(", ")}`).toEqual([]);
	});
});

/**
 * Files still pending migration (E4.9b batches B2–B4), with the batch that
 * removes them. This is a burn-down list: it may only shrink. A file not on it
 * must contain no fixed Chinese, so the check blocks *new* hard-coded text
 * while the remaining batches land.
 */
const PENDING: Record<string, "B2" | "B3" | "B4"> = {
	// Empty since E4.9b: every learning component is translated. Keep the map so
	// a future batch can register a file explicitly instead of loosening the scan.
};

/**
 * Files that legitimately keep Chinese: user/AI content rendered verbatim, or
 * deliberate Chinese-only strings. Each entry needs a reason.
 */
const ALLOWED_CHINESE: Array<{ file: string; reason: string }> = [
	// Populated as batches complete; an empty list means every learning file is
	// either translated or listed in PENDING.
];

const CJK = /[一-鿿]/;
const BLOCK_COMMENT = /\/\*[\s\S]*?\*\//g;
const LINE_COMMENT = /(?<!:)\/\/[^\n]*/g;
/** `t("key", "中文兜底")` — the fallback is a resource, not hard-coded UI text. */
const T_WITH_DEFAULT = /t\(\s*"[^"]*"\s*,\s*"[^"]*"(?:\s*,\s*\{[^}]*\})?\s*\)/g;

/** Strip comments and translation fallbacks before looking for fixed Chinese. */
function fixedChinese(source: string): boolean {
	const stripped = source
		.replace(BLOCK_COMMENT, "")
		.replace(LINE_COMMENT, "")
		.replace(T_WITH_DEFAULT, 't("")');
	return CJK.test(stripped);
}

describe("learning UI hard-coded Chinese", () => {
	it("does not contain unregistered fixed Chinese outside allowed files", async () => {
		const root = new URL("../react/", import.meta.url);
		const files: string[] = [];
		async function walk(dir: URL, prefix = ""): Promise<void> {
			for (const entry of await readdir(dir, { withFileTypes: true })) {
				const child = new URL(`${entry.name}${entry.isDirectory() ? "/" : ""}`, dir);
				const path = `${prefix}${entry.name}`;
				if (entry.isDirectory()) await walk(child, `${path}/`);
				else if (/\.(tsx|ts)$/.test(entry.name) && !entry.name.includes(".test.")) files.push(path);
			}
		}
		await walk(root);
		expect(files.length).toBeGreaterThan(0);

		const allowed = new Set(ALLOWED_CHINESE.map((entry) => entry.file));
		const offenders: string[] = [];
		for (const file of files) {
			if (allowed.has(file)) continue;
			if (PENDING[file]) continue;
			const source = await readFile(new URL(file, root), "utf-8");
			if (fixedChinese(source)) offenders.push(file);
		}
		expect(offenders, `untranslated files: ${offenders.join(", ")}`).toEqual([]);
	}, 30_000);
});
